"""Durable storage for explicitly isolated synthetic fixtures only."""
import hashlib
import json
import os
import secrets
import sqlite3
import stat
import tempfile
from contextlib import contextmanager
from pathlib import Path


class SyntheticStore:
    def __init__(self, source, resume_root=None):
        if resume_root is None:
            self.root = Path(tempfile.mkdtemp(prefix='gsub-onlyoffice-synthetic-')).resolve()
            os.chmod(self.root, 0o700)
            self.secrets = {'secret': secrets.token_hex(32), 'actors': {role: secrets.token_urlsafe(32) for role in ('author', 'editor', 'other')}}
            credentials = self.root / 'fixture-secrets.json'
            fd = os.open(credentials, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
            with os.fdopen(fd, 'w') as f:
                json.dump(self.secrets, f)
                f.flush()
                os.fsync(f.fileno())
            self.db = self.root / 'synthetic.sqlite'
            # O_EXCL prevents accidentally opening an existing database.
            fd = os.open(self.db, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
            os.close(fd)
            with self.transaction() as c:
                c.executescript('''BEGIN IMMEDIATE;
                CREATE TABLE fixture (id TEXT PRIMARY KEY CHECK(id='synthetic-1'), title TEXT NOT NULL);
                CREATE TABLE versions (manuscript TEXT NOT NULL REFERENCES fixture(id), number INTEGER NOT NULL CHECK(number>0), name TEXT NOT NULL UNIQUE, sha256 TEXT NOT NULL CHECK(length(sha256)=64), byte_size INTEGER NOT NULL CHECK(byte_size BETWEEN 1 AND 10485760), PRIMARY KEY(manuscript,number));
                CREATE TABLE sessions (key TEXT PRIMARY KEY, manuscript TEXT NOT NULL REFERENCES fixture(id), actor TEXT NOT NULL CHECK(actor IN ('author','editor')), source_version INTEGER NOT NULL, head INTEGER NOT NULL, expires REAL NOT NULL, closed INTEGER NOT NULL DEFAULT 0 CHECK(closed IN (0,1)), revoked INTEGER NOT NULL DEFAULT 0 CHECK(revoked IN (0,1)), FOREIGN KEY(manuscript,source_version) REFERENCES versions(manuscript,number), FOREIGN KEY(manuscript,head) REFERENCES versions(manuscript,number));
                CREATE TABLE callbacks (session_key TEXT NOT NULL REFERENCES sessions(key), event_hash TEXT NOT NULL CHECK(length(event_hash)=64), status INTEGER NOT NULL CHECK(status IN (1,2,3,4,6,7)), digest TEXT, PRIMARY KEY(session_key,event_hash));
                CREATE TABLE save_urls (session_key TEXT NOT NULL REFERENCES sessions(key), url_hash TEXT NOT NULL, digest TEXT NOT NULL, PRIMARY KEY(session_key,url_hash));
                CREATE TRIGGER immutable_versions_update BEFORE UPDATE ON versions BEGIN SELECT RAISE(ABORT,'immutable version'); END;
                CREATE TRIGGER immutable_versions_delete BEFORE DELETE ON versions BEGIN SELECT RAISE(ABORT,'immutable version'); END;
                CREATE TRIGGER immutable_callbacks_update BEFORE UPDATE ON callbacks BEGIN SELECT RAISE(ABORT,'immutable callback'); END;
                CREATE TRIGGER immutable_callbacks_delete BEFORE DELETE ON callbacks BEGIN SELECT RAISE(ABORT,'immutable callback'); END;
                ''')
                c.execute("INSERT INTO fixture VALUES ('synthetic-1','Synthetic manuscript')")
                self.write_version(c, source, 1)
        else:
            path = Path(resume_root)
            # Only roots generated by this adapter beneath the operating system's temp root.
            temp = Path(tempfile.gettempdir()).resolve()
            if (not path.is_absolute() or path.is_symlink() or not path.is_dir()
                    or not path.name.startswith('gsub-onlyoffice-synthetic-')
                    or path.resolve().parent != temp or stat.S_IMODE(path.stat().st_mode) & 0o077):
                raise ValueError('Unsafe synthetic root')
            self.root = path.resolve()
            self.db = self.root / 'synthetic.sqlite'
            credentials = self.root / 'fixture-secrets.json'
            for file in (self.db, credentials):
                if file.is_symlink() or not file.is_file() or file.stat().st_nlink != 1 or stat.S_IMODE(file.stat().st_mode) & 0o077:
                    raise ValueError('Missing or unsafe fixture state')
            self.secrets = json.loads(credentials.read_text())
            with self.transaction() as c:
                if c.execute('SELECT id FROM fixture').fetchall() != [('synthetic-1',)]:
                    raise ValueError('Incompatible fixture')
                original = c.execute("SELECT name,sha256,byte_size FROM versions WHERE manuscript='synthetic-1' AND number=1").fetchone()
                if original is None:
                    raise ValueError('Synthetic source missing')
                original_bytes = self.read_file(original)
                if source is not None and original_bytes != source:
                    raise ValueError('Synthetic source mismatch')

    @contextmanager
    def transaction(self):
        c = sqlite3.connect(self.db, timeout=5, isolation_level=None)
        try:
            c.execute('PRAGMA foreign_keys=ON')
            c.execute('BEGIN IMMEDIATE')
            yield c
            c.commit()
        except BaseException:
            c.rollback()
            raise
        finally:
            c.close()

    def write_version(self, c, data, number):
        name = secrets.token_hex(24) + '.docx'
        path = self.root / name
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, 'O_NOFOLLOW', 0), 0o600)
        with os.fdopen(fd, 'wb') as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        digest = hashlib.sha256(data).hexdigest()
        # A failed DB operation can leave an orphan; never delete it automatically.
        c.execute('INSERT INTO versions VALUES (?,?,?,?,?)', ('synthetic-1', number, name, digest, len(data)))
        return digest

    def read_file(self, entry):
        name, digest, size = entry
        if not isinstance(name, str) or len(name) != 53 or not name.endswith('.docx') or any(ch not in '0123456789abcdef' for ch in name[:-5]) or not 0 < size <= 10 * 1024 * 1024:
            raise ValueError('Invalid file metadata')
        fd = os.open(self.root / name, os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0))
        with os.fdopen(fd, 'rb') as f:
            st = os.fstat(f.fileno())
            if not stat.S_ISREG(st.st_mode) or st.st_nlink != 1:
                raise ValueError('Invalid stored file')
            data = f.read(size + 1)
        if len(data) != size or hashlib.sha256(data).hexdigest() != digest:
            raise ValueError('File integrity failure')
        return data
